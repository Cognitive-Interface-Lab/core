import type { CompletionSpec } from "./spec.js";

/** A self-contained bash (4+) script that defines `_core` and runs `complete -F _core core`. */
export function bashScript(spec: CompletionSpec): string {
  const list = (words: string[]) => words.map(quote).join(" ");
  const cases = Object.entries(spec.commands).map(([name, command]) =>
    [
      `    ${quote(name)})`,
      `      opts=(${list(command.options)})`,
      `      vopts=(${list(command.valueOptions)})`,
      `      pos=${quote(command.positional ?? "none")}`,
      "      ;;",
    ].join("\n"),
  );

  return `# bash completion for core (bash 4 or newer). Generated by "core completion bash";
# run that again after updating core.

_core_in() {
  local word="$1" item
  shift
  for item in "$@"; do
    [[ $item == "$word" ]] && return 0
  done
  return 1
}

_core() {
  local -a commands=(${list(Object.keys(spec.commands))})
  local -a global=(${list(spec.globalOptions)})
  local -a providers=(${list(spec.providers)})
  local -a actions=(${list(spec.configActions)})
  local -a keys=(${list(spec.configKeys)})
  local -a shells=(${list(spec.shells)})

  # Words come from COMP_LINE: COMP_WORDS splits at ":", which breaks provider:model routes.
  local line="\${COMP_LINE:0:COMP_POINT}"
  local -a words=()
  read -r -a words <<< "$line"
  local cur=""
  if [[ ! $line =~ [[:space:]]$ ]] && (( \${#words[@]} > 0 )); then
    cur="\${words[\${#words[@]}-1]}"
    unset "words[\${#words[@]}-1]"
  fi
  local count=\${#words[@]}
  local prog="\${words[0]}"
  local -a cands=()
  local route=0 i
  COMPREPLY=()

  if (( count <= 1 )); then
    if [[ $cur == -* ]]; then
      cands=("\${global[@]}")
    else
      cands=("\${commands[@]}")
    fi
  else
    local -a opts=() vopts=()
    local pos
    case "\${words[1]}" in
${cases.join("\n")}
    *)
      return 0
      ;;
    esac

    local prev="\${words[count-1]}"
    if (( count > 2 )) && _core_in "$prev" "\${vopts[@]}"; then
      [[ $prev == --model ]] && route=1
    elif [[ $cur == -* ]]; then
      cands=("\${opts[@]}")
    else
      local -a args=()
      local skip=0
      for (( i = 2; i < count; i++ )); do
        if (( skip )); then
          skip=0
        elif [[ \${words[i]} == -* ]]; then
          _core_in "\${words[i]}" "\${vopts[@]}" && skip=1
        else
          args+=("\${words[i]}")
        fi
      done
      if (( \${#args[@]} == 0 )); then
        case "$pos" in
        command) cands=("\${commands[@]}") ;;
        provider) cands=("\${providers[@]}") ;;
        shell) cands=("\${shells[@]}") ;;
        config) cands=("\${actions[@]}") ;;
        esac
      elif [[ $pos == config ]]; then
        if (( \${#args[@]} == 1 )) && _core_in "\${args[0]}" get set unset; then
          cands=("\${keys[@]}")
        elif (( \${#args[@]} == 2 )) && [[ \${args[0]} == set && \${args[1]} == route ]]; then
          route=1
        fi
      fi
    fi
  fi

  if (( route )); then
    local candidate
    while IFS= read -r candidate; do
      cands+=("$candidate")
    done < <("$prog" __complete route "$cur" 2>/dev/null)
  fi

  local -a matches=()
  local candidate
  for candidate in "\${cands[@]}"; do
    [[ $candidate == "$cur"* ]] && matches+=("$candidate")
  done

  # Bash replaces only the text after the last ":" of the current word.
  if [[ $cur == *:* ]]; then
    local prefix="\${cur%:*}:"
    for i in "\${!matches[@]}"; do
      matches[i]="\${matches[i]:\${#prefix}}"
    done
  fi

  COMPREPLY=("\${matches[@]}")
  if (( \${#COMPREPLY[@]} == 1 )) && [[ \${COMPREPLY[0]} == *[:,] ]]; then
    compopt -o nospace 2>/dev/null
  fi
  return 0
}

complete -F _core core
`;
}

/** Single-quotes a word for bash; a word that would need escaping is a bug in the spec. */
function quote(word: string): string {
  if (/['\s\\]/.test(word)) throw new Error(`cannot embed ${JSON.stringify(word)} in the completion script`);
  return `'${word}'`;
}
